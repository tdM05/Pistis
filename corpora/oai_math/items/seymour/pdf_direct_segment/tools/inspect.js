#!/usr/bin/env node
// inspect.js — headless, LLM-readable view of an annotation. Resolves tree.json
// offsets to real PDF text (chars.txt) and Lean text, prints the box tree with
// labels/counts/lean/links, and runs the SAME validation as the UI (core.js +
// schema.json). No browser, no pdf.js at runtime.
//
//   node tools/inspect.js [subtreeId]      # whole tree, or just a box's subtree
//   node tools/inspect.js --errors         # only boxes with issues
//   node tools/inspect.js --raw <id>       # dump one box's raw json + resolved text
//   node tools/inspect.js --vars [scopeId] # variable coreference groups per scope
//   node tools/inspect.js --fol <id>       # render a box to FOL + its signature
//
// (chars.txt is regenerated by tools/extract_chars.js when paper.pdf changes.)
import { readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';
import { makeCore } from '../core.js';

const dir = path.dirname(fileURLToPath(import.meta.url));
const R = path.resolve(dir, '..');
const schema = JSON.parse(readFileSync(path.join(R, 'schema.json'), 'utf8'));
const ROOT = JSON.parse(readFileSync(path.join(R, 'tree.json'), 'utf8'));
if (!existsSync(path.join(R, 'chars.txt'))) { console.error('missing chars.txt — run: node tools/extract_chars.js'); process.exit(1); }
const CHARS = readFileSync(path.join(R, 'chars.txt'), 'utf8');
const C = makeCore(schema);

// lazy lean-file cache (resolve lean spans to text)
const leanCache = {};
const leanText = (file) => { if (leanCache[file] == null) { const p = path.join(R, file); leanCache[file] = existsSync(p) ? readFileSync(p, 'utf8') : ''; } return leanCache[file]; };

const args = process.argv.slice(2);
const errorsOnly = args.includes('--errors');
const rawIdx = args.indexOf('--raw');
const varsIdx = args.indexOf('--vars');
const folIdx = args.indexOf('--fol');
// positional id = first bare arg that isn't a flag's value
const flagVals = new Set([rawIdx, varsIdx, folIdx].filter((i) => i >= 0).map((i) => args[i + 1]));
const subId = args.find((a) => !a.startsWith('--') && !flagVals.has(a));

const snippet = (s, n = 50) => s.replace(/\s+/g, ' ').trim().slice(0, n);
const boxText = (b) => { const ps = C.pieces(b); return ps.length ? ps.map((p) => CHARS.slice(p.start, p.end)).join(' ⋯ ') : (b.implicit ? '(implicit)' : '(no span)'); };

// --raw: one box, full detail
if (rawIdx >= 0) {
  const id = args[rawIdx + 1]; const b = C.find(ROOT, id);
  if (!b) { console.error('no such box: ' + id); process.exit(1); }
  console.log('id:', b.id);
  console.log('label:', JSON.stringify(b.label || null), b.label ? '→ tag ' + C.labelTag(ROOT, b) : '');
  console.log('count:', b.count ?? '(unset)');
  if (C.isVariable(b)) { const sc = C.scopeOf(ROOT, b); console.log('var:', b.var ?? '(unset)', '· scope:', sc === ROOT ? 'root' : sc.id); }
  console.log('implicit:', !!b.implicit);
  console.log('pieces:', JSON.stringify(C.pieces(b)));
  console.log('text:', JSON.stringify(boxText(b)));
  if (b.lean) console.log('lean:', JSON.stringify(b.lean), b.lean.spans ? '\n  → ' + b.lean.spans.map((s) => JSON.stringify(snippet(leanText(s.file).slice(s.start, s.end), 60))).join('\n  → ') : '');
  const ds = C.derivedSymbol(ROOT, b); if (ds) console.log('derived symbol:', ds.sym, '(' + ds.reason + ')');
  console.log('issues:', JSON.stringify(C.boxIssues(b)));
  console.log('children:', (b.children || []).map((c) => c.id).join(', ') || '(none)');
  process.exit(0);
}

// --fol: render a box to a FOL formula + its signature
if (folIdx >= 0) {
  const id = args[folIdx + 1]; const b = C.find(ROOT, id);
  if (!b) { console.error('no such box: ' + id); process.exit(1); }
  const symText = (x) => { const ps = C.pieces(x); if (!ps.length) return '∅'; return CHARS.slice(ps[0].start, ps[0].end).replace(/\s+/g, ' ').trim().replace(/ /g, '_'); };
  const { str, sig } = C.toFOL(ROOT, b, symText);
  console.log('FOL:\n  ' + str);
  console.log('\nsignature:');
  const fmt = (o) => Object.entries(o).map(([k, n]) => `${k}/${n}`).join(', ') || '—';
  console.log('  relations:', fmt(sig.rel));
  console.log('  functions:', fmt(sig.fn));
  console.log('  constants:', fmt(sig.con));
  console.log('  variables:', [...sig.vars].join(', ') || '—');
  process.exit(0);
}

// --vars: variable coreference groups, keyed by each variable's ACTUAL scope
// (scopeOf = nearest def/theorem, else top-level box) — so a variable is listed
// under exactly one scope, not every ancestor.
if (varsIdx >= 0) {
  const only = args[varsIdx + 1] && !args[varsIdx + 1].startsWith('--') ? args[varsIdx + 1] : null;
  const byScope = new Map();   // scopeBox -> {name -> [boxes]}
  C.walk(ROOT, (n) => { if (n === ROOT || !C.isVariable(n)) return;
    const sc = C.scopeOf(ROOT, n);
    if (!byScope.has(sc)) byScope.set(sc, {});
    const g = byScope.get(sc); const k = n.var || '(unnamed)'; (g[k] = g[k] || []).push(n); });
  for (const [sc, groups] of byScope) {
    if (only && sc.id !== only) continue;
    const lbl = sc === ROOT ? 'root' : (sc.label ? C.labelTag(ROOT, sc) : 'top');
    console.log(`\nscope ${sc === ROOT ? 'root' : sc.id} [${lbl}] "${snippet(boxText(sc), 40)}"`);
    for (const [name, boxes] of Object.entries(groups).sort()) {
      const texts = boxes.map((b) => { const t = snippet(boxText(b), 16); return `${b.id}:${t || '∅'}`; });
      const flag = name === '(unnamed)' ? ' ⚠unnamed' : (boxes.length === 1 ? '' : ' (corefs)');
      console.log(`  ${name}${flag}: ${texts.join('  ')}`);
    }
  }
  process.exit(0);
}

// tree print
const linkmap = {};
(ROOT.links || []).forEach((l) => { (linkmap[l.from] = linkmap[l.from] || []).push('→' + l.to); (linkmap[l.to] = linkmap[l.to] || []).push('←' + l.from); });

const out = [];
const start = subId ? C.find(ROOT, subId) : ROOT;
if (!start) { console.error('no such box: ' + subId); process.exit(1); }
const baseDepth = subId ? 0 : 0;
const printNode = (n, d) => {
  if (n !== ROOT) {
    const iss = C.boxIssues(n);
    if (errorsOnly && !iss.length) { /* still recurse */ }
    else {
      const tag = n.label ? C.labelTag(ROOT, n) : '·unlabelled';
      const vn = (C.isVariable(n) && n.var != null) ? ` =${n.var}` : '';
      const cnt = n.count != null ? ` #${n.count}` : '';
      const lean = n.lean ? (n.lean.none ? ' [lean:∅]' : ` [lean:${(n.lean.spans || []).length}]`) : '';
      const lk = linkmap[n.id] ? ' ' + linkmap[n.id].join(' ') : '';
      const im = n.implicit ? ' ∅impl' : '';
      // derived-symbol reason (why this symbol token is what it is)
      const ds = n.label ? C.derivedSymbol(ROOT, n) : null;
      const dsn = ds ? ` {${ds.reason}}` : '';
      // coverage % for non-leaf boxes with children (how well children tile it)
      let cov = '';
      const concrete = n.label && C.labelConcrete(n.label);
      if (n.children && n.children.length && concrete && !C.isLeafLabel(concrete)) {
        const cv = C.coverageOf(n); if (cv.total) cov = ` [cov:${Math.round(100 * cv.covered / cv.total)}%${cv.gaps.length ? ',' + cv.gaps.length + 'gap' : ''}]`;
      }
      const warn = iss.length ? '  ⚠ ' + iss.join('; ') : '';
      out.push(`${'  '.repeat(d)}${n.id} [${tag}${vn}]${cnt}${im}${lean}${cov}${lk}${dsn}  "${snippet(boxText(n))}"${warn}`);
    }
  }
  (n.children || []).forEach((c) => printNode(c, d + 1));
};
if (start === ROOT) { out.push(`paper  links=${JSON.stringify(ROOT.links || [])}`); (ROOT.children || []).forEach((c) => printNode(c, 0)); }
else printNode(start, 0);

// validation summary
const issues = C.allIssues(ROOT);
console.log(out.join('\n'));
console.log('\n── validation ──');
if (!issues.length) console.log('✓ no structural issues');
else { console.log(`${issues.length} box(es) with issues:`); issues.forEach(({ id, box, issues }) => console.log(`  ${id} [${box.label ? C.labelTag(ROOT, box) : 'unlabelled'}]: ${issues.join('; ')}`)); }
